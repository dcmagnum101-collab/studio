#!/usr/bin/env node
/**
 * scripts/embed-credentials.js
 *
 * Run before `next build`. Reads .env.local from the repo root and writes
 * electron/bundled-credentials.js — a plain JS module with all credential
 * values baked in. This file gets bundled into the .app so Monica never
 * needs to enter credentials on first launch.
 *
 * If .env.local is missing or a key is absent, the value is set to '' and
 * the app falls back to showing a setup screen for those services only.
 *
 * Usage: node scripts/embed-credentials.js
 */

const fs = require('fs');
const path = require('path');

const ENV_PATH = path.join(__dirname, '../.env.local');
const OUT_PATH = path.join(__dirname, '../electron/bundled-credentials.js');

const REQUIRED_KEYS = [
  'NEXT_PUBLIC_FIREBASE_API_KEY',
  'NEXT_PUBLIC_FIREBASE_AUTH_DOMAIN',
  'NEXT_PUBLIC_FIREBASE_PROJECT_ID',
  'NEXT_PUBLIC_FIREBASE_STORAGE_BUCKET',
  'NEXT_PUBLIC_FIREBASE_MESSAGING_SENDER_ID',
  'NEXT_PUBLIC_FIREBASE_APP_ID',
  'FIREBASE_ADMIN_PROJECT_ID',
  'FIREBASE_ADMIN_CLIENT_EMAIL',
  'FIREBASE_ADMIN_PRIVATE_KEY',
  'GROK_API_KEY',
  'TWILIO_ACCOUNT_SID',
  'TWILIO_AUTH_TOKEN',
  'TWILIO_PHONE_NUMBER',
  'NEXT_PUBLIC_GOOGLE_MAPS_KEY',
];

// Parse .env.local style file (KEY=VALUE, supports multi-line private keys)
function parseEnvFile(content) {
  const result = {};
  const lines = content.split('\n');
  let current = null;
  for (const line of lines) {
    if (!current) {
      // Skip comments and blank lines
      if (!line || line.startsWith('#')) continue;
      const eqIdx = line.indexOf('=');
      if (eqIdx === -1) continue;
      const key = line.slice(0, eqIdx).trim();
      let val = line.slice(eqIdx + 1).trim();
      // Strip surrounding quotes
      if ((val.startsWith('"') && val.endsWith('"')) ||
          (val.startsWith("'") && val.endsWith("'"))) {
        val = val.slice(1, -1);
      }
      // Detect unclosed quote (multi-line value like FIREBASE_ADMIN_PRIVATE_KEY)
      if (val.startsWith('"') && !val.endsWith('"')) {
        current = { key, val: val.slice(1) };
      } else {
        result[key] = val.replace(/\\n/g, '\n');
      }
    } else {
      if (line.endsWith('"')) {
        result[current.key] = (current.val + '\n' + line.slice(0, -1)).replace(/\\n/g, '\n');
        current = null;
      } else {
        current.val += '\n' + line;
      }
    }
  }
  return result;
}

let envVars = {};
if (fs.existsSync(ENV_PATH)) {
  const content = fs.readFileSync(ENV_PATH, 'utf-8');
  envVars = parseEnvFile(content);
  console.log('✓ Read .env.local');
} else {
  console.warn('⚠  .env.local not found — bundling empty credentials (setup screen will appear)');
}

// Report what was found
const found = REQUIRED_KEYS.filter(k => envVars[k]);
const missing = REQUIRED_KEYS.filter(k => !envVars[k]);
if (found.length) console.log(`✓ Found ${found.length} credential(s):`, found.map(k => k.split('_').slice(-1)[0]).join(', '));
if (missing.length) console.warn(`⚠  Missing ${missing.length} key(s):`, missing.join(', '));

// Write output module
const entries = REQUIRED_KEYS.map(key => {
  const val = (envVars[key] || '').replace(/\\/g, '\\\\').replace(/`/g, '\\`');
  return `  '${key}': \`${val}\``;
});

const output = `// AUTO-GENERATED by scripts/embed-credentials.js — DO NOT EDIT MANUALLY
// Regenerate by running: node scripts/embed-credentials.js
'use strict';

module.exports = {
${entries.join(',\n')},
};
`;

fs.writeFileSync(OUT_PATH, output, 'utf-8');
console.log(`✓ Wrote electron/bundled-credentials.js (${found.length}/${REQUIRED_KEYS.length} keys populated)`);

if (missing.length > 0 && !envVars['NEXT_PUBLIC_FIREBASE_PROJECT_ID']) {
  console.warn('\n⚠  NEXT_PUBLIC_FIREBASE_PROJECT_ID is missing.');
  console.warn('   The app will show a first-launch setup screen instead of the dashboard.');
  console.warn('   Add your Firebase credentials to .env.local and re-run this script.\n');
}
